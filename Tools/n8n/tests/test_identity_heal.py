def mint(install=INST, u=U, exp_in=3600, secret=SECRET):
    """A capability token exactly as Issue Token signs it (token.js: v1.<b64url payload>.<b64url HMAC-SHA256>)."""
    return run_js("""const s = require('crypto');
const b64u = (b) => Buffer.from(b).toString('base64').replace(/\\+/g,'-').replace(/\\//g,'_').replace(/=+$/,'');
const v = $input.first().json;
const p = b64u(JSON.stringify(v.claims));
return [{json: {t: 'v1.' + p + '.' + b64u(s.createHmac('sha256', v.secret).update('v1.' + p).digest())}}];""",
                  {'json': {'secret': secret, 'claims': {'i': install, 'u': u, 'p': [], 'w': [], 'c': [],
                                                         'e': int(time.time()) + exp_in, 'n': 1}}})[0]['json']['t']


