#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""B1 «расписание бота» (2026-10-14; spec docs/superpowers/specs/2026-10-14-paying-users-protection-and-schedule-design.md
§4 B1, §1) — the owner's schedule reaches the server through ONE webhook:

  crSetSchedule001-Set_Schedule.json   POST /webhook/SetSchedule
                                       {profileIds:[…], enabled, daysMask, startMin, endMin, timeZone, version}
      Auth Gate (token ONLY: legacy false — a new endpoint has no old client; every profileIds entry must be one of the
      token's profiles, the sentinels '-1' / '' pass) → Authorized? → Validate (the ids taken again from the body: the
      sentinels dropped, the rest re-intersected with the token's profiles, de-duplicated — one statement touches a row
      once —, at most ten; enabled a boolean, daysMask 0..127, startMin / endMin 0..1439, timeZone an IANA-shaped name or
      UTC, version a positive integer) → Valid? → Upsert Schedule (ONE statement for every profile — all rows or none —,
      version-guarded: a row is written only over an OLDER stored version, so a delayed retry or a reordered request
      never overwrites a newer desire; per profile, in the request's order, it reports applied + the version the server
      holds) → Shape Response
      → Respond {success:true, results:[{profileId, applied, version}]}.
      Refusals: 401 / 403 from the gate; 400 bad_request + reason (a malformed body); 400 bad_timezone (a zone that passes
      the shape but Postgres does not know, e.g. Europe/Nowhere: the table's trigger bot_schedule_tz_check is the final
      arbiter and its refusal is the client's mistake, never a 500); 500 db_unavailable (any other database fault — Upsert
      Schedule continues on error, so Shape Response judges the rows, never «the node continued»). The contract of Set
      Reply Mode v2 (apply-reply-mode-v2.py).
  0DP79STI3pafXO9B-Set_Workflow_State.json  crSetSchedule001 joins the protected infra ids. The other three dependents of
      build-client-webhooks.PROTECTED_IDS — Create WA/TG (apply-clone-lifecycle.py), Delete Bot Files (apply-auth-gate.py
      + apply-history-handoff.py) and the Profile Lifecycle Sweep (apply-sweep-clone-deactivate.py) — take it from there.

The table: sql/2026-10-14-bot-schedule.sql (apply BEFORE importing this workflow). The schedule is READ by the bot
templates' Read Reply Mode (the predicate lives in bot_schedule.py); this workflow only writes it.

    python3 Tools/n8n/build-set-schedule.py            # write the workflow + patch Set Workflow State (re-runnable)
    python3 Tools/n8n/build-set-schedule.py --check    # exit 2 when anything is stale
Pinned by verify-set-schedule.py (structure) and tests/test_set_schedule.py (behaviour on real SQL + the verifier's
negatives on scratch copies).
"""
import importlib.util
import json
import os
import sys
import uuid

HERE = os.path.dirname(os.path.abspath(__file__))
WF = os.path.join(HERE, "workflows")


def _module(name, filename):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, filename))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


auth = _module("build_auth", "build-auth-workflows.py")

WF_ID, WF_NAME = "crSetSchedule001", "Set Schedule"
WF_FILE = f"{WF_ID}-Set_Schedule.json"
PATH = "SetSchedule"
SET_STATE = "0DP79STI3pafXO9B-Set_Workflow_State.json"
PROTECTED_ANCHOR = "  'crChannelWatch001'\n]);"
RULE = {"profiles": ["profileIds"], "workflows": [], "appUser": [], "legacy": False}
MAX_PROFILES = 10
# An IANA zone name (Area/Location[/Sub], Etc/GMT+5) or UTC — the SHAPE only; whether Postgres knows the zone is the
# table's trigger's call (Europe/Nowhere passes here and is refused there as bad_timezone).
TZ_PATTERN = r"^[A-Za-z_]+(?:/[A-Za-z0-9_+\-]+)+$|^UTC$"
TZ_MAX_LEN = 64
TZ_MARKER = "bot_schedule_bad_timezone"      # the trigger's message prefix (sql/2026-10-14-bot-schedule.sql)


def vid(name):
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "set-schedule:" + name))


VALIDATE_JS = r"""// SET SCHEDULE / Validate (generated by Tools/n8n/build-set-schedule.py — edit there, never the JSON).
// The gate already refused a profile id the token does not own. Here the ids are taken again from the body: the sentinels
// ('-1', '') dropped, the rest re-intersected with the token's profiles (the statement only ever sees the caller's own),
// de-duplicated (one statement may touch a row once), at most __MAX__ (a bot has two). Every field of the schedule is
// required, also for a disabled one (re-enabling restores the window the owner set).
const wh = $input.first().json || {};
const b = (wh.body && typeof wh.body === 'object') ? wh.body : {};
const owned = new Set((wh.crAuth && wh.crAuth.profiles) || []);
const bad = (reason) => [{ json: { ok: false, error: 'bad_request', reason }, pairedItem: { item: 0 } }];
if (!Array.isArray(b.profileIds)) return bad('profileIds');
const ids = Array.from(new Set(b.profileIds.filter((x) => typeof x === 'string' && x !== '' && x !== '-1' && owned.has(x)))).slice(0, __MAX__);
if (ids.length === 0) return bad('profileIds');
if (typeof b.enabled !== 'boolean') return bad('enabled');
const within = (v, lo, hi) => Number.isInteger(v) && v >= lo && v <= hi;
if (!within(b.daysMask, 0, 127)) return bad('daysMask');
if (!within(b.startMin, 0, 1439)) return bad('startMin');
if (!within(b.endMin, 0, 1439)) return bad('endMin');
const tz = typeof b.timeZone === 'string' ? b.timeZone : '';
if (tz.length > __TZ_MAX__ || !/__TZ__/.test(tz)) return bad('timeZone');
const v = b.version;
const version = (Number.isInteger(v) && v > 0 && v <= Number.MAX_SAFE_INTEGER) ? v
  : ((typeof v === 'string' && /^[1-9][0-9]*$/.test(v) && v.length <= 16 && Number(v) <= Number.MAX_SAFE_INTEGER) ? Number(v) : 0);
if (!version) return bad('version');
return [{ json: { ok: true, profileIds: ids, enabled: b.enabled, daysMask: b.daysMask, startMin: b.startMin, endMin: b.endMin,
                  timeZone: tz, version }, pairedItem: { item: 0 } }];
""".replace("__MAX__", str(MAX_PROFILES)).replace("__TZ_MAX__", str(TZ_MAX_LEN)).replace("__TZ__", TZ_PATTERN.replace("/", "\\/"))

UPSERT_SQL = """-- B1 «расписание бота» (2026-10-14): the owner's schedule for every requested profile of the bot, in ONE statement — all
-- rows or none. A row is written only when the stored version is OLDER than the request's (a delayed retry or a reordered
-- request never overwrites a newer desire); per profile, in the order of the request, the answer says whether it was
-- applied and which version the server holds now (the pre-statement row for a stale request: a data-modifying CTE is
-- invisible to the rest of the same statement). The zone is checked by the table's own trigger (bot_schedule_tz_check):
-- an unknown one fails the whole statement, which Shape Response answers as bad_timezone.
-- Parameters, in order: JSON array of the profile ids, enabled, days mask, start minute, end minute, time zone, version.
with req as (
  select t.profile_id, t.n from jsonb_array_elements_text($1::jsonb) with ordinality as t(profile_id, n)
), up as (
  insert into bot_schedule (profile_id, enabled, days_mask, start_min, end_min, tz, version, updated_at)
  select r.profile_id, $2::boolean, $3::int, $4::int, $5::int, $6::text, $7::bigint, now() from req r
  on conflict (profile_id) do update
    set enabled = excluded.enabled, days_mask = excluded.days_mask, start_min = excluded.start_min,
        end_min = excluded.end_min, tz = excluded.tz, version = excluded.version, updated_at = now()
    where bot_schedule.version < excluded.version
  returning profile_id, version
)
select r.profile_id as "profileId", (up.profile_id is not null) as applied,
       coalesce(up.version, cur.version, 0)::bigint as version
from req r
left join up on up.profile_id = r.profile_id
left join bot_schedule cur on cur.profile_id = r.profile_id
order by r.n;"""
UPSERT_PARAMS = ("={{ [ JSON.stringify($json.profileIds), $json.enabled, $json.daysMask, $json.startMin, $json.endMin, "
                 "$json.timeZone, $json.version ] }}")

SHAPE_JS = r"""// SET SCHEDULE / Shape Response (generated by Tools/n8n/build-set-schedule.py — edit there, never the JSON).
// Upsert Schedule continues on error: a database fault reaches here as an item carrying `message` / `error`, never as
// «the node continued». Success = exactly one row per requested profile, each naming its profile and a boolean
// `applied`. A zone Postgres does not know is refused by the table's trigger with a message starting with
// __MARKER__ — the client's mistake (400 bad_timezone); every other fault is the server's (500 db_unavailable).
const v = $('Validate').first().json;
const rows = $input.all().map((i) => i.json).filter((r) => r && typeof r === 'object');
const requested = Array.isArray(v.profileIds) ? v.profileIds : [];
const ok = rows.length === requested.length && rows.length > 0
  && rows.every((r) => r.error === undefined && typeof r.profileId === 'string' && typeof r.applied === 'boolean');
if (!ok) {
  const said = rows.map((r) => String(r.message || '') + ' ' + String((r.error && r.error.message) || '')).join(' ');
  if (said.includes('__MARKER__')) return [{ json: { success: false, error: 'bad_timezone', _status: 400 }, pairedItem: { item: 0 } }];
  return [{ json: { success: false, error: 'db_unavailable', _status: 500 }, pairedItem: { item: 0 } }];
}
const results = rows.map((r) => ({ profileId: r.profileId, applied: r.applied === true, version: Number(r.version) || 0 }));
return [{ json: { success: true, results, _status: 200 }, pairedItem: { item: 0 } }];""".replace("__MARKER__", TZ_MARKER)

RESPOND_401_BODY = "={{ { success: false, error: 'unauthorized', reason: $json.crAuth.reason } }}"
RESPOND_401_CODE = "={{ String($json.crAuth.reason || '').startsWith('forbidden') ? 403 : 401 }}"
RESPOND_400_BODY = "={{ { success: false, error: 'bad_request', reason: $json.reason } }}"


def own(n):
    n["id"] = vid(n["name"])
    return n


def respond_400(pos):
    return {"parameters": {"respondWith": "json", "responseBody": RESPOND_400_BODY, "options": {"responseCode": 400}},
            "id": vid("Respond 400"), "name": "Respond 400", "type": "n8n-nodes-base.respondToWebhook", "typeVersion": 1.5,
            "position": pos}


def build():
    n, c = [], {}
    wh = auth.webhook(PATH, [0, 300])
    wh["id"], wh["webhookId"] = vid("webhook:" + PATH), vid("webhookId:" + PATH)
    n.append(wh)
    n.append(own(auth.code("Auth Gate", auth.gate_code(RULE), [220, 300])))
    n.append(own(auth.if_true("Authorized?", "={{ $json.crAuth.ok }}", [440, 300])))
    n.append(own(auth.respond("Respond 401", [660, 520], body=RESPOND_401_BODY, code_expr=RESPOND_401_CODE)))
    n.append(own(auth.code("Validate", VALIDATE_JS, [660, 200])))
    n.append(own(auth.if_true("Valid?", "={{ $json.ok }}", [880, 200])))
    n.append(respond_400([1100, 420]))
    n.append(own(auth.postgres("Upsert Schedule", UPSERT_SQL, UPSERT_PARAMS, [1100, 100])))
    n.append(own(auth.code("Shape Response", SHAPE_JS, [1320, 100])))
    n.append(own(auth.respond("Respond", [1540, 100])))
    auth.edge(c, "Webhook", "Auth Gate")
    auth.edge(c, "Auth Gate", "Authorized?")
    auth.edge(c, "Authorized?", "Validate", 0)
    auth.edge(c, "Authorized?", "Respond 401", 1)
    auth.edge(c, "Validate", "Valid?")
    auth.edge(c, "Valid?", "Upsert Schedule", 0)
    auth.edge(c, "Valid?", "Respond 400", 1)
    auth.edge(c, "Upsert Schedule", "Shape Response")
    auth.edge(c, "Shape Response", "Respond")
    settings = {"executionOrder": "v1", "saveDataSuccessExecution": "none", "saveDataErrorExecution": "all", "saveManualExecutions": False}
    return auth.workflow(WF_ID, WF_NAME, n, c, settings)


def text():
    return json.dumps(build(), indent=2, ensure_ascii=False) + "\n"


def protected_js_patched(js):
    """Set Workflow State's Validate with crSetSchedule001 appended to its protected list (None: nothing to change)."""
    if "const PROTECTED = new Set([" not in js or f"'{WF_ID}'" in js:
        return None
    assert js.count(PROTECTED_ANCHOR) == 1, "Set Workflow State: the protected list has an unexpected shape"
    return js.replace(PROTECTED_ANCHOR, f"  'crChannelWatch001',\n  '{WF_ID}'\n]);")


def patch_set_state(write):
    path = os.path.join(WF, SET_STATE)
    wf = json.load(open(path, encoding="utf-8"))
    changed = False
    for nd in wf["nodes"]:
        new = protected_js_patched(nd["parameters"].get("jsCode", ""))
        if new is not None:
            nd["parameters"]["jsCode"] = new
            changed = True
    if changed and write:
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(wf, fh, indent=2, ensure_ascii=False)
            fh.write("\n")
    return changed


def stale():
    out = []
    p = os.path.join(WF, WF_FILE)
    if not os.path.exists(p) or open(p, encoding="utf-8").read() != text():
        out.append(WF_FILE)
    wf = json.load(open(os.path.join(WF, SET_STATE), encoding="utf-8"))
    if not any(f"'{WF_ID}'" in nd["parameters"].get("jsCode", "") for nd in wf["nodes"]):
        out.append(SET_STATE)
    return out


def main():
    if "--check" in sys.argv:
        s = stale()
        print("set schedule:", "OK" if not s else f"STALE {s}")
        sys.exit(2 if s else 0)
    path = os.path.join(WF, WF_FILE)
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    new = text()
    if old != new:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(new)
    print(f"{'wrote' if old != new else 'up to date'}  {WF_FILE} ({len(build()['nodes'])} nodes)")
    print(f"{'patched' if patch_set_state(write=True) else 'up to date'}  {SET_STATE} (protected ids)")


if __name__ == "__main__":
    main()
