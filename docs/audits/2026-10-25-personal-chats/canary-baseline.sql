-- «Личные и рабочие чаты» — отметка начала canary (README пакета, шаг 9.0; только чтение). Выполнять ПРЯМО ПЕРЕД 9.1.
-- canary.sql (шаг 9.5) судит от этой отметки решения, рабочий чат 9.1, журнал ответа по состояниям и память личных чатов;
-- историю и журнал ответа личного чата он сверяет со временем решения по этому чату (оно позже выкладки, но может быть и раньше
-- отметки). Всё, что ИИ-сотрудник сохранил до решения (до выкладки — о каждом своём чате один на один), остаётся на сервере и в
-- оценку не входит. У памяти (n8n_chat_histories) нет колонки времени, поэтому «после» для неё — id больше отметки; для
-- остального — время записи. Отсюда два числа: момент (UTC, до микросекунд) и последний id памяти.
-- Ожидание: {"baseline_at":"<время>Z","memory_max_id":"<число>"}. Вывод сохраняется в canary-baseline.txt (tee) — его читает
-- canary.py, который и подставляет отметку в canary.sql.
-- Прод: через Tools/n8n/.secrets/sql-oneoff.py (команда — README пакета, шаг 9.0).
select to_char(now() at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"') as baseline_at,
       (select coalesce(max(m.id), 0) from public.n8n_chat_histories m)::text as memory_max_id;
